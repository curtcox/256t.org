#!/usr/bin/env python3
"""Bundle our own dependency-free modules as a classic browser script.

This entry point lets Firefox install import maps before its first module load.
It does not transform provider JavaScript or use runtime eval.
"""
from pathlib import Path


def build():
    root = Path(__file__).resolve().parents[1]
    cid = (root / "implementations/ecmascript/cid.js").read_text()
    uri = (root / "implementations/ecmascript/uri.mjs").read_text()
    uri = uri.replace("import * as namespace from './cid.js';", "")
    uri = uri.replace("const cidLibrary = namespace.default ?? globalThis.t256Cid;", "const cidLibrary = globalThis.t256Cid;")
    uri = uri.replace("export ", "")
    loader = (root / "browser-support/web/loader.mjs").read_text()
    loader = loader.replace("import { parseUri, readVerified } from '../../implementations/ecmascript/uri.mjs';", "const { parseUri, readVerified } = globalThis.t256URI;")
    loader = loader.replace("export class T256Client", "class T256Client")
    text = "// Generated by browser-support/build_loader.py; edit the original modules.\n"
    text += "(() => {\nconst module = undefined;\n" + cid + "\n})();\n"
    text += "(() => {\n" + uri + "\nglobalThis.t256URI = { computeCid, parseUri, verifyUri, readVerified, mediaType };\n})();\n"
    text += "(() => {\n" + loader + "\nglobalThis.T256Client = T256Client;\n})();\n"
    target = root / "browser-support/web/loader.js"
    target.write_text(text)


if __name__ == "__main__": build()
